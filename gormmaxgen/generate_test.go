package gormmaxgen

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"gorm.io/gorm"

	"gorm-max/example/model"
)

// GenStatus 自定义命名类型:生成器应精确映射为 TypedField[GenStatus]。
type GenStatus int

// GenTag 自定义切片类型(unnamed 复合类型走 GenericField 的对照)。
type GenTag []string

// GenUser 测试模型,覆盖各字段类型映射分支。
type GenUser struct {
	ID        int64  `gorm:"primaryKey"`
	Name      string `gorm:"size:64"`
	Age       int
	Status    GenStatus `gorm:"column:status"`
	Score     float64
	Active    bool
	CreatedAt time.Time
	DeletedAt gorm.DeletedAt `gorm:"index"`
	Avatar    []byte
	Tags      GenTag         `gorm:"serializer:json"` // 命名复合类型 → 精确到原类型
	Extra     map[string]any `gorm:"serializer:json"` // unnamed 复合类型 → GenericField 兜底
	Remark    string         `gorm:"column:remark"`
}

func TestGenerateContent(t *testing.T) {
	src, err := build(Config{Models: []any{&GenUser{}}})
	if err != nil {
		t.Fatalf("build: %v", err)
	}
	s := string(src)

	for _, want := range []string{
		"// Code generated by gormmaxgen. DO NOT EDIT.",
		"package query",
		`gorm_max "gorm-max"`,
		"type GenUserFields struct {",
		"gorm_max.Int64Field",
		"gorm_max.StringField",
		"gorm_max.IntField",
		// 自定义命名类型 → 精确到原类型(含命名切片)
		"gorm_max.TypedField[gormmaxgen.GenStatus]",
		`gorm_max.NewTyped[gormmaxgen.GenStatus]("status")`,
		"gorm_max.TypedField[gormmaxgen.GenTag]",
		"Score     gorm_max.Float64Field",
		"Active    gorm_max.BoolField",
		// GORM 语义:time / bytes
		"CreatedAt gorm_max.TimeField",
		"DeletedAt gorm_max.TimeField",
		"Avatar    gorm_max.BytesField",
		// unnamed 复合类型兜底
		"Extra     gorm_max.GenericField",
		// 显式 column tag 生效
		`gorm_max.NewString("remark")`,
		"var GenUser = GenUserFields{",
	} {
		if !strings.Contains(s, want) {
			t.Errorf("生成内容缺少 %q:\n%s", want, s)
		}
	}
}

func TestGenerateDeterministic(t *testing.T) {
	a, err := build(Config{Models: []any{&GenUser{}, &model.User{}}})
	if err != nil {
		t.Fatalf("build a: %v", err)
	}
	b, err := build(Config{Models: []any{&model.User{}, &GenUser{}}}) // 传入顺序不同
	if err != nil {
		t.Fatalf("build b: %v", err)
	}
	if string(a) != string(b) {
		t.Fatal("相同模型集合的两次生成结果应完全一致(确定性输出)")
	}
	// 两模型都在,且按名排序(GenUser 在 User 前)
	s := string(a)
	if strings.Index(s, "var GenUser") > strings.Index(s, "var User") {
		t.Error("模型应按类型名排序")
	}
}

func TestGenerateSameTypeDedup(t *testing.T) {
	// 同一模型重复传入:忽略,不报错
	src, err := build(Config{Models: []any{&GenUser{}, &GenUser{}}})
	if err != nil {
		t.Fatalf("build: %v", err)
	}
	if n := strings.Count(string(src), "var GenUser ="); n != 1 {
		t.Fatalf("重复模型应去重: %d", n)
	}
}

func TestGenerateWritesFile(t *testing.T) {
	out := filepath.Join(t.TempDir(), "query", "fields_gen.go")
	if err := Generate(Config{Out: out, Models: []any{&GenUser{}}}); err != nil {
		t.Fatalf("generate: %v", err)
	}
	if _, err := os.Stat(out); err != nil {
		t.Fatalf("输出文件应存在: %v", err)
	}
}

func TestGenerateErrors(t *testing.T) {
	if _, err := build(Config{}); err == nil {
		t.Error("空 Models 应报错")
	}
	if _, err := build(Config{Models: []any{nil}}); err == nil {
		t.Error("nil 模型应报错")
	}
	if _, err := build(Config{Models: []any{struct{ ID int64 }{}}}); err == nil {
		t.Error("匿名结构体应报错")
	}
}

// TestExampleArtifactUpToDate 仓库内的 example/query/fields_gen.go 必须与当前生成器输出一致,
// 防止生成器改动后示例产物过期(金样即真实产物)。
func TestExampleArtifactUpToDate(t *testing.T) {
	want, err := build(Config{Out: "query/fields_gen.go", Models: []any{&model.User{}}})
	if err != nil {
		t.Fatalf("build: %v", err)
	}
	got, err := os.ReadFile(filepath.Join("..", "example", "query", "fields_gen.go"))
	if err != nil {
		t.Fatalf("读取示例产物: %v", err)
	}
	if string(got) != string(want) {
		t.Fatal("example/query/fields_gen.go 与生成器输出不一致,请在 example/ 下重新运行 go run ./gen/main.go")
	}
}
